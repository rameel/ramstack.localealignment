using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Ramstack.LocaleAlignment.Generator;

[Generator]
public sealed class LocaleAlignmentGenerator : IIncrementalGenerator
{
    private static readonly string s_source = LoadImplSource();

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var version = context.CompilationProvider.Select((c, _) => GetLanguageVersion(c));
        context.RegisterSourceOutput(version, GenerateLocaleInitializer);
    }

    private static LanguageVersion? GetLanguageVersion(Compilation compilation)
    {
        //
        // Only applications get the initializer. In a library, it would run on first access
        // and override the culture the application has already chosen.
        //

        if (compilation.Options.OutputKind is not (OutputKind.ConsoleApplication or OutputKind.WindowsApplication))
            return null;

        if (compilation is CSharpCompilation csharp)
            return csharp.LanguageVersion;

        return null;
    }

    private static void GenerateLocaleInitializer(SourceProductionContext context, LanguageVersion? version)
    {
        if (version is null)
            return;

        // File-local types require C# 11
        var modifier = version <= LanguageVersion.CSharp10 ? "internal" : "file";

        //
        // The code is compiled only for .NET 6 and later, so applications that also target
        // older frameworks, such as .NET Framework, still build.
        //

        var source = $$"""
            // <auto-generated />
            #if NET6_0_OR_GREATER
            using System;
            using System.Globalization;

            #nullable enable

            [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]
            {{modifier}} static class LocaleAlignment
            {
                [global::System.Runtime.CompilerServices.ModuleInitializer]
                public static void Apply() =>
                    LocaleAlignmentImpl.Apply();

            {{s_source}}
            }
            #endif

            """;

        context.AddSource("LocaleAlignment.g.cs", SourceText.From(source.Replace("\r\n", "\n"), Encoding.UTF8));
    }

    private static string LoadImplSource()
    {
        //
        // LocaleAlignmentImpl.cs from the library, indented to be nested into the generated class.
        //

        using var stream = typeof(LocaleAlignmentGenerator).Assembly.GetManifestResourceStream("LocaleAlignmentImpl.cs")!;
        using var reader = new StreamReader(stream);

        var lines = reader.ReadToEnd().TrimEnd().Split('\n');
        return string.Join("\n", lines.Select(line => line.Trim('\r').Length == 0 ? line : "    " + line));
    }
}
